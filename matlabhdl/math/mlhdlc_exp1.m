function y_fp = mlhdlc_exp1(x)
%% Algorithm that builds 'exp' from first principles
% f(x) = exp(x)
% decompse x into two parts
% integer part  n and small fraction part f
% x = n *log(2) + f; log(2) is a constant (natural log) and f is a small
% fraction
% |f| < log(2)/2;
% exp(x) = exp((n * log(2)) + f);
% exp(x) = exp(n *log(2)) * exp(f); exp(a +b) = exp(a) *exp(b);
% exp(n*log(2)) = exp(log(2)) ^ n;  a^( n*m) = (a^n)^m;power rule
% exp(log(2)) = 2;
% exp(n * log(2) = 2^n;
% exp(x) = (2^n) * exp(f);
% use LUT based linear interpolation method for fraction part
% exp(x) = (2^n) * exp(f);
% extract integer part of the input using 
% n = floor(x/log(2));
% multiply with inverse log(2)
% n = floor(x *inverselog(2));
% n = n + floor(f *inverselog(2))

%% End of algorithm
% to increase the precision select or change outFL

    % Check if the input is a fixed-point type
    if isfi(x)
        % Extract word length and fraction length from input
        InWL = x.WordLength;
        InFL = x.FractionLength;
        % Assert that the fraction length is non-negative
        assert(InFL >= 0, 'Fraction length must be non-negative.');
    else
        error('Input must be fixed point.');
    end
    
    % Define the fixed-point data type using derived parameters
    %% select the output precision
    OutFL = 16;
    %% Derive Types
    % determine the output wordlength for a given input type
    % This is determined based on the max float value that can occur for a
    % given input types

    % for example for 3 integer bits and 4 fractional bits and one sign bit
    % the max possible input is [-8 to 7.9375]
    % exp(8) is the max possible value
    % exp(8) approximately 3000
    % ceil(log2(3000))  = 12 bits are required to represent integer part of the output

    maxIntpart = ceil(log2(exp(2^(InWL - InFL - 1))));
    OutWL = maxIntpart + OutFL;

    InputType = numerictype('WordLength', InWL, 'FractionLength', InFL);
    ln2Type = numerictype(0, OutWL,  OutWL);
    Invln2Type = numerictype(0, OutWL,  OutWL-1);
    IntPartType = numerictype(1,  maxIntpart,0);
    FractionPartType = numerictype(0, OutWL,  OutWL-1);
    OutType = numerictype(0, OutWL,  OutFL);
    x_fp = fi(x,InputType);
    % Constants in fixed-point
    ln2_fp = fi(log(2),ln2Type);  % ln(2)
    inv_ln2_fp = fi(1/(log(2)),Invln2Type);  % 1/ln(2)
    % Range reduction: x = n * ln(2) + f
    n_fp = fi(floor(x_fp * inv_ln2_fp),IntPartType);  % Integer part
    f_fp = fi(x_fp - n_fp * ln2_fp,FractionPartType);      % Fractional part
    exp_f = exp_core_top(f_fp);
    % Combine results: e^x = 2^n * e^f
    shift_amount = (n_fp);  
    const2 = fi(1,OutType);
    power_2 = fi(bitshift(const2, shift_amount),OutType);
    y_fp = fi(power_2 * exp_f,OutType);
    
end



function y = exp_core_top( x )
    fm = get_fimath();
    OutWL = x.WordLength;
    OutFL = OutWL -2;
    x_in = fi( x, 0, OutWL, OutWL-1, fm );
    y = fi(exp_core(x_in), 0, OutWL, OutFL, fm);
end

